/**
 * Compiles every `yul/<devnet>/<Opcode>.yul` and writes the creation codes into `contracts/generated/HelperCode.sol`,
 * the one place Solidity can read them from. Run by `yarn build:helpers`; CI fails when the committed output is stale.
 *
 * Conventions, checked here so a typo fails loudly:
 *  - a directory `yul/erc8421-workshop` is the `Devnet.ERC8421_WORKSHOP` member of contracts/Devnet.sol
 *  - a file `FrameDataLoad.yul` is the `Opcode.FrameDataLoad` member of contracts/Opcode.sol, and holds an object
 *    of the same name
 *
 * solc-js, not forge, compiles the Yul: the optimizer is off and the version is pinned, so the output is
 * reproducible and does not depend on forge's artifact layout.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const solc = createRequire(import.meta.url)("solc");
const EVM_VERSION = "paris"; // keep equal to evm_version in foundry.toml

const members = (file) => {
  const body = fs.readFileSync(`${root}contracts/${file}`, "utf8").match(/enum \w+ \{([\s\S]*?)\}/)?.[1] ?? "";
  return body.replace(/\/\/.*|\/\*[\s\S]*?\*\//g, "").split(",").map((m) => m.trim()).filter(Boolean);
};
const devnets = members("Devnet.sol");
const opcodes = members("Opcode.sol");
const upperSnake = (kebab) => kebab.toUpperCase().replaceAll("-", "_");
const lowerFirst = (s) => s[0].toLowerCase() + s.slice(1);

function compile(file, name) {
  const out = JSON.parse(
    solc.compile(
      JSON.stringify({
        language: "Yul",
        sources: { [path.basename(file)]: { content: fs.readFileSync(file, "utf8") } },
        settings: { evmVersion: EVM_VERSION, optimizer: { enabled: false }, outputSelection: { "*": { "*": ["evm.bytecode.object"] } } },
      }),
    ),
  );
  const errors = (out.errors ?? []).filter((e) => e.severity === "error");
  if (errors.length > 0) throw new Error(errors.map((e) => e.formattedMessage).join("\n"));
  const contract = Object.values(out.contracts ?? {})[0]?.[name];
  if (!contract) throw new Error(`${file}: no object named "${name}"`);
  return contract.evm.bytecode.object;
}

// devnet member -> opcode member -> creation code
const code = new Map();
for (const dir of fs.readdirSync(`${root}yul`).sort()) {
  const devnet = upperSnake(dir);
  if (!devnets.includes(devnet)) throw new Error(`yul/${dir}: contracts/Devnet.sol has no member ${devnet}`);
  const byOpcode = new Map();
  for (const f of fs.readdirSync(`${root}yul/${dir}`).sort()) {
    const opcode = f.replace(/\.yul$/, "");
    if (!f.endsWith(".yul") || !opcodes.includes(opcode)) throw new Error(`yul/${dir}/${f}: contracts/Opcode.sol has no member ${opcode}`);
    byOpcode.set(opcode, compile(`${root}yul/${dir}/${f}`, opcode));
  }
  code.set(devnet, byOpcode);
}

const fn = (opcode) => {
  const cases = devnets
    .filter((d) => code.get(d)?.has(opcode))
    .map((d) => `        if (devnet == Devnet.${d}) return hex"${code.get(d).get(opcode)}";`);
  return `    function ${lowerFirst(opcode)}(Devnet devnet) internal pure returns (bytes memory) {\n${cases.join("\n")}${cases.length ? "\n" : ""}        return "";\n    }`;
};

const version = solc.version().split("+")[0];
fs.writeFileSync(
  `${root}contracts/generated/HelperCode.sol`,
  `// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

import {Devnet} from "../Devnet.sol";

// GENERATED by \`yarn build:helpers\` from yul/ (solc ${version}, evm ${EVM_VERSION}, optimizer off). Do not edit.

/// The creation code of every Yul helper, per devnet. Empty where the devnet does not have the opcode.
library HelperCode {
${opcodes.map(fn).join("\n\n")}
}
`,
);
console.log(`wrote ${[...code.values()].reduce((n, m) => n + m.size, 0)} helper(s) for ${code.size} devnet(s) with solc ${version}`);
